from pathlib import Path
from typing import Protocol

from breeze.jobs import Job
from breeze.models import Recognition, Transcript


class AudioConverter(Protocol):
    def available(self) -> bool: ...

    def to_wav(self, source: Path, destination: Path) -> None: ...


class SpeechRecognizer(Protocol):
    def available(self) -> bool: ...

    def loaded(self) -> bool: ...

    def device_name(self) -> str: ...

    def transcribe(self, wav_path: Path) -> Recognition: ...


class TranscriptStoreFactory(Protocol):
    def for_user(self, user_id: str) -> "TranscriptRepository": ...


class TranscriptRepository(Protocol):
    def save(self, transcript: Transcript) -> Transcript: ...

    def list_all(self) -> list[Transcript]: ...

    def get(self, transcript_id: str) -> Transcript | None: ...

    def delete(self, transcript_id: str) -> bool: ...


class MeetingSummarizer(Protocol):
    def summarize_transcript(self, transcript: Transcript, output_dir: Path) -> Path: ...


class TagSuggester(Protocol):
    def suggest(self, text: str) -> list[str]: ...


class JobRepository(Protocol):
    def create(self, job: Job) -> Job: ...

    def get(self, job_id: str) -> Job | None: ...

    def update(self, job_id: str, **changes) -> Job | None: ...
